#!/usr/bin/env python3
"""Build a readable, self-contained installer for existing private AI laptops."""
import argparse
import hashlib
from pathlib import Path

REPOSITORY = Path(__file__).resolve().parents[2]
FILES = (
    "scripts/local-ai/windows/Setup-ActivityMedia.ps1",
    "scripts/local-ai/windows/Setup-Gateway.ps1",
    "scripts/local-ai/windows/Setup-ActivityImages.ps1",
    "scripts/local-ai/image-downloads.json",
    "scripts/local-ai/windows/activity_image_worker.py",
    "scripts/local-ai/windows/activity_image_engine.py",
    "scripts/local-ai/windows/run-activity-images.py",
    "scripts/local-ai/windows/activity_image_layouts.py",
)
HEADER = r'''#Requires -Version 5.1
# Generated by scripts/local-ai/build-activity-media.py from reviewed source.
# Adopts the existing private gateway and installed SDXL runtime. No model download.
[CmdletBinding()]
param([switch]$Check, [switch]$Update, [switch]$Recover, [switch]$Diagnose)
$ErrorActionPreference = 'Stop'
function Assert-SkaoMediaToolPath {
    param([string]$Path)
    $candidate = [IO.Path]::GetFullPath($Path)
    while ($candidate) {
        if (Test-Path -LiteralPath $candidate) {
            $item = Get-Item -LiteralPath $candidate -Force
            if ($item.Attributes -band [IO.FileAttributes]::ReparsePoint) {
                throw 'AI_MEDIA_PATH: A tool path contains a linked entry; it was preserved.'
            }
        }
        $parent = [IO.Directory]::GetParent($candidate)
        if (!$parent) { break }
        $candidate = $parent.FullName
    }
}
try {
    if (!$env:LOCALAPPDATA) { throw 'AI_MEDIA_ACCOUNT: LOCALAPPDATA is unavailable for this account.' }
'''
FOOTER = r'''
    if ($Recover -and !$Update) { throw 'AI_MEDIA_OPTIONS: -Recover requires -Update.' }
    if (([int][bool]$Check + [int][bool]$Update + [int][bool]$Diagnose) -gt 1) { throw 'AI_MEDIA_OPTIONS: Choose only one operation.' }
    if ($Diagnose) {
        # Diagnose directly from the packaged definitions, without extracting
        # code, creating directories, changing settings, or starting inference.
        try {
            . ([scriptblock]::Create($payload[0].Content))
            Get-SkaoActivityMediaDiagnostic -Context (Get-SkaoActivityMediaContext)
        }
        catch { throw 'AI_MEDIA_DIAGNOSTIC: The protected worker summary could not be read. No settings were changed.' }
        exit 0
    }
    Assert-SkaoMediaToolPath -Path $toolRoot
    foreach ($entry in $payload) {
        $target = Join-Path $toolRoot $entry.Path
        Assert-SkaoMediaToolPath -Path $target
        if (Test-Path -LiteralPath $target) {
            if (!(Test-Path -LiteralPath $target -PathType Leaf) -or
                (Get-FileHash -LiteralPath $target -Algorithm SHA256).Hash -ine $entry.Sha256) {
                throw 'AI_MEDIA_TOOL_CONFLICT: A saved companion differs; it was preserved.'
            }
        }
        elseif ($Check -or $Diagnose) {
            throw 'AI_MEDIA_NOT_CONFIGURED: Run this file once without -Check. Check mode made no changes.'
        }
        else {
            [void](New-Item -ItemType Directory -Path (Split-Path -Parent $target) -Force)
            $bytes = (New-Object Text.UTF8Encoding($false)).GetBytes($entry.Content)
            $stream = New-Object IO.FileStream($target, [IO.FileMode]::CreateNew, [IO.FileAccess]::Write, [IO.FileShare]::None)
            try { $stream.Write($bytes, 0, $bytes.Length) }
            finally { $stream.Dispose() }
            if ((Get-FileHash -LiteralPath $target -Algorithm SHA256).Hash -ine $entry.Sha256) {
                throw 'AI_MEDIA_TOOL_HASH: A companion could not be written correctly.'
            }
        }
    }
    & (Join-Path $toolRoot 'scripts/local-ai/windows/Setup-ActivityMedia.ps1') -Check:$Check -Update:$Update -Recover:$Recover -Diagnose:$Diagnose
    exit $LASTEXITCODE
}
catch {
    Write-Error $_.Exception.Message -ErrorAction Continue
    exit 1
}
'''


def build(output: Path):
    payload = []
    for relative in FILES:
        content = (REPOSITORY / relative).read_text(encoding="utf-8-sig")
        payload.append((relative, hashlib.sha256(content.encode()).hexdigest(), content))
    identity = hashlib.sha256("\n".join(path + ":" + sha for path, sha, _ in payload).encode()).hexdigest()[:20]
    text = HEADER + "    $toolRoot = Join-Path $env:LOCALAPPDATA 'SKAO-ActivityMediaTools/" + identity + "'\n"
    text += "    $payload = @(\n"
    for relative, sha, content in payload:
        # Ordinary multiline single-quoted literals allow nested PS here-strings.
        # A doubled quote is literal in PowerShell, including at line boundaries.
        text += "        @{ Path = '" + relative + "'; Sha256 = '" + sha + "'; Content = '"
        text += content.replace("'", "''") + "' }\n"
    text += "    )\n" + FOOTER
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_bytes(b"\xef\xbb\xbf" + text.encode())
    print("Built " + str(output.resolve()))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    build(parser.parse_args().output)
